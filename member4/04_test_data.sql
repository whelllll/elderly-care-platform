GO

/* 同一设备不应有两条未解绑记录，期望 0 行 */
SELECT device_sn, COUNT(*) AS active_count
FROM dbo.monitor_device
WHERE unbind_time IS NULL
GROUP BY device_sn
HAVING COUNT(*) > 1;
GO

/* 事件状态分布 */
